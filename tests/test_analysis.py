#!/usr/bin/env python3
"""
test_analysis.py
Unit tests for FlowMonitor XML parsing, metric calculations, and safe divide-by-zero guards.
"""

import unittest
import os
import sys
import tempfile
import xml.etree.ElementTree as ET

# Add python directory to path
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(BASE_DIR, "python"))

from analyze_results import parse_ns_time, parse_flowmon_xml


class TestAnalysis(unittest.TestCase):

    def test_parse_ns_time(self):
        """Test time parsing from ns-3 string representations."""
        self.assertAlmostEqual(parse_ns_time("+1e+09ns"), 1.0)
        self.assertAlmostEqual(parse_ns_time("+2.5s"), 2.5)
        self.assertAlmostEqual(parse_ns_time("500ms"), 0.5)
        self.assertAlmostEqual(parse_ns_time(0.0), 0.0)
        self.assertAlmostEqual(parse_ns_time(""), 0.0)

    def test_missing_xml_file(self):
        """Test that missing XML files return an empty list gracefully."""
        res = parse_flowmon_xml("non_existent_file.xml")
        self.assertEqual(res, [])

    def test_zero_packet_flow_guard(self):
        """Test that zero-packet flows return 'N/A' rather than NaN or crashing."""
        dummy_xml = """<?xml version="1.0" ?>
<FlowMonitor>
  <FlowStats>
    <Flow flowId="1" timeFirstTxPacket="+0.0ns" timeLastRxPacket="+0.0ns"
          txPackets="0" rxPackets="0" txBytes="0" rxBytes="0" lostPackets="0"
          delaySum="+0.0ns" jitterSum="+0.0ns">
    </Flow>
  </FlowStats>
  <Ipv4FlowClassifier>
    <Flow flowId="1" sourceAddress="10.1.1.1" destinationAddress="10.1.4.2" protocol="6" sourcePort="1234" destinationPort="50000" />
  </Ipv4FlowClassifier>
</FlowMonitor>"""
        with tempfile.NamedTemporaryFile("w", delete=False, suffix=".xml") as f:
            f.write(dummy_xml)
            temp_path = f.name

        try:
            flows = parse_flowmon_xml(temp_path)
            self.assertEqual(len(flows), 1)
            f0 = flows[0]
            self.assertEqual(f0["PDR_percent"], "N/A")
            self.assertEqual(f0["PacketLoss_percent"], "N/A")
            self.assertEqual(f0["AvgDelay_ms"], "N/A")
            self.assertEqual(f0["AvgJitter_ms"], "N/A")
            self.assertEqual(f0["Throughput_Mbps"], 0.0)
        finally:
            os.remove(temp_path)

    def test_real_flowmon_parsing(self):
        """Test parsing an actual FlowMonitor output generated by our NS-3 simulation."""
        xml_file = os.path.join(BASE_DIR, "results", "raw", "exp1_queue_50p-flowmon.xml")
        if os.path.exists(xml_file):
            flows = parse_flowmon_xml(xml_file)
            self.assertGreater(len(flows), 0)
            for f in flows:
                self.assertIn("FlowID", f)
                self.assertIn("PDR_percent", f)
                self.assertIn("Throughput_Mbps", f)
                self.assertIn("AvgDelay_ms", f)


if __name__ == "__main__":
    unittest.main()
